"""Find likely function entry points in a dumped Xbox 360 image that the
ReXGlue analyzer misses (no RTTI, so its vtable scanner finds nothing).

The image is the decrypted XEX (default.xex.decrypt) or a flat dump; its
sections come from its PE headers. Candidates inside a .pdata function are
dropped (switch-case labels after a bctr, whose lis/addi jump-table bases
look like pointers, split real functions; --keep-inside-pdata keeps them),
and so are XEX import thunks (hinted, they leave undefined sub_ symbols). A
candidate on a .pdata function's start or end counts as an entry even after
a bl (a leaf function after a call that doesn't return).

Sources of candidates:
  - 32-bit words in .rdata/.data that point into .text (vtables, callbacks)
  - lis/addi (or lis/ori) address constants in .text (member-function pointers)
A candidate is kept only if it looks like a function entry, not a label inside
a function.

Usage:
  scan_ptrs.py <default.xex.decrypt | image dump> [manifest.toml]
               [--toml out.toml] [--all-code] [--keep-inside-pdata]
Without --toml, prints one 0xXXXXXXXX per line.
"""
import argparse
import bisect
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xex_image  # noqa: E402

TOML_HEADER = """\
# Function entry points found by scanning the loaded image for code pointers
# (vtables, thunks, lis/addi constants). The game has no RTTI, so ReXGlue's
# own vtable scanner finds nothing. Generated by tools/scan_ptrs.py (then
# tools/prune.py); regenerate rather than hand-edit.

[functions]
"""

BLR, BCTR = 0x4E800020, 0x4E800420
MFLR_R12 = 0x7D8802A6


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('image')
    ap.add_argument('manifest', nargs='?')
    ap.add_argument('--toml', help='write a [functions] include file here')
    ap.add_argument('--all-code', action='store_true',
                    help='treat every executable section as code, not just .text')
    ap.add_argument('--keep-inside-pdata', action='store_true',
                    help="keep candidates that fall inside a .pdata function's body")
    args = ap.parse_args()

    img = xex_image.load(args.image)
    text_ranges = img.code_ranges(args.all_code)
    data_ranges = img.data_ranges()
    if not text_ranges or not data_ranges:
        sys.exit('no .text/.rdata/.data sections found (is this an Xbox 360 image?)')
    for lo, hi in text_ranges:
        print(f'code {lo:08X}-{hi:08X}', file=sys.stderr)
    for lo, hi in data_ranges:
        print(f'data {lo:08X}-{hi:08X}', file=sys.stderr)

    def word(addr):
        return img.word(addr) if img.contains(addr) else 0

    def in_text(v):
        return v % 4 == 0 and any(lo <= v < hi for lo, hi in text_ranges)

    def is_uncond_b(i):
        return (i >> 26) == 18 and (i & 3) == 0  # b, not bl/ba

    def entry_shape(ins):
        # this-adjustor thunk (addi r3,r3,imm), standard prologue, or vcall
        # thunk (lwz r12,0(r3|r4)).
        return (ins >> 16) == 0x3863 or ins == MFLR_R12 or ins in (0x81830000, 0x81840000)

    # .pdata starts and ends are real function boundaries. An end matters for
    # leaf functions (no .pdata entry of their own) placed right after a
    # function whose last instruction is a call that doesn't return (bl, not
    # blr): e.g. the qsort comparator at 0x82383C30, reached only through a
    # lis/addi pointer, which the rules below reject.
    pdata_all = img.pdata_functions()
    boundaries = {b for b, _ in pdata_all} | {b + n for b, n in pdata_all}

    def plausible_start(t, loose_after_b):
        prev, ins = word(t - 4), word(t)
        if t in boundaries:
            return True
        if prev in (BLR, BCTR, 0):  # nothing can fall through into t
            return True
        if is_uncond_b(prev):       # could be a switch-case label instead
            return entry_shape(ins) or loose_after_b
        return False

    def jump_table_like(addr):
        # Switch tables are runs of code pointers that all land close together.
        run = [addr]
        for step in (-4, 4):
            a = addr + step
            while in_text(word(a)) and len(run) < 64:
                run.append(a)
                a += step
        if len(run) < 3:
            return False
        vals = [word(a) for a in run]
        return max(vals) - min(vals) < 0x800

    cands = {}
    for lo, hi in data_ranges:
        for a in range(lo, hi - 3, 4):
            v = word(a)
            if in_text(v) and plausible_start(v, loose_after_b=not jump_table_like(a)):
                cands.setdefault(v, 'data')

    # lis rD,hi ; ... ; addi/ori rX,rD,lo within a short window
    for tlo, thi in text_ranges:
        for a in range(tlo, thi - 4, 4):
            i = word(a)
            if (i >> 26) != 15 or ((i >> 16) & 31) != 0:  # lis = addis rD,0,imm
                continue
            rd, hi = (i >> 21) & 31, (i & 0xFFFF) << 16
            for b in range(a + 4, min(a + 4 * 12, thi), 4):
                j = word(b)
                op, ra = j >> 26, (j >> 16) & 31
                if ra == rd and op in (14, 24):  # addi / ori
                    lo = j & 0xFFFF
                    v = (hi + (lo - 0x10000 if op == 14 and lo & 0x8000 else lo)) & 0xFFFFFFFF
                    if in_text(v) and plausible_start(v, loose_after_b=False):
                        cands.setdefault(v, 'code')
                    break
                if ((j >> 21) & 31) == rd and op not in (36, 37, 38, 44, 45, 47):
                    break  # rD overwritten (not a store)

    # XEX import thunks (two import records, then mtctr r11; bctr) sit at the
    # end of .text and data points at them, so they look like entries. The
    # SDK turns them into imports; hinting one as a function leaves calls to
    # an undefined sub_XXXXXXXX (link error), so drop them.
    def import_thunk(a):
        return ((word(a) >> 24) == 0x01 and (word(a + 4) >> 24) == 0x02
                and word(a + 8) == 0x7D6903A6 and word(a + 12) == BCTR)
    thunks = [c for c in cands if import_thunk(c)]
    for c in thunks:
        del cands[c]
    print(f"dropped {len(thunks)} import thunks", file=sys.stderr)

    if not args.keep_inside_pdata:
        pdata = img.pdata_functions()
        starts = [b for b, _ in pdata]

        def inside(a):
            i = bisect.bisect_right(starts, a) - 1
            return i >= 0 and starts[i] < a < starts[i] + pdata[i][1]
        dropped = [c for c in cands if inside(c)]
        for c in dropped:
            del cands[c]
        print(f"dropped {len(dropped)} inside .pdata functions ({len(pdata)} in .pdata)",
              file=sys.stderr)

    n_data = sum(1 for k in cands.values() if k == 'data')
    print(f"candidates: {len(cands)} ({n_data} from data, {len(cands) - n_data} from code)",
          file=sys.stderr)
    if args.manifest:
        hinted = set(int(a, 16) for a in re.findall(
            r'^(0x[0-9A-Fa-f]+) = \{\}', open(args.manifest).read(), re.M))
        print(f"loop-found hints covered: {len(hinted & set(cands))}/{len(hinted)}; missed: "
              f"{[hex(h) for h in sorted(hinted - set(cands))]}", file=sys.stderr)

    if args.toml:
        with open(args.toml, 'w', newline='\n') as f:
            f.write(TOML_HEADER)
            for c in sorted(cands):
                f.write(f"0x{c:08X} = {{}}\n")
        print(f"wrote {len(cands)} entries to {args.toml}", file=sys.stderr)
    else:
        for c in sorted(cands):
            print(f"0x{c:08X}")


if __name__ == '__main__':
    main()
