"""Writes sbx_recomp/src/graphics/compiled_shaders.h: the shaders the game's
HLSL compiler (D3DXCompileShader, sub_822B3678) makes at boot, as it made
them, for the hardcoded shaders (src/hooks/shader_compiles.cpp). Adapted
from ITC-Recomp's itc_recomp/tools/compiled_shaders.py; the source's length
comes from the dump's file name, so no image is needed.

  python -I sbx_recomp/tools/compiled_shaders.py <dump dir>

<dump dir> holds shader_<source>_<length>_<profile>.bin, as a run with
--dump_shader_compiles=<dump dir> writes them.
"""
import os
import re
import sys

dump_dir = sys.argv[1]

shaders = []
for name in sorted(os.listdir(dump_dir)):
    m = re.fullmatch(r'shader_([0-9A-F]{8})_(\d+)_([vp]s_\d_\d)\.bin', name)
    if not m:
        continue
    source, length, profile = int(m.group(1), 16), int(m.group(2)), m.group(3)
    data = open(os.path.join(dump_dir, name), 'rb').read()
    shaders.append((source, length, profile, data))

out = []
out.append('// Generated by sbx_recomp/tools/compiled_shaders.py: the shaders the game\'s')
out.append('// HLSL compiler (sub_822B3678) makes at boot from source in the image, as it')
out.append('// made them (big-endian, as in guest memory). See src/hooks/shader_compiles.cpp')
out.append('// (src/hooks/shader_compiles.cpp).')
out.append('')
out.append('#pragma once')
out.append('')
out.append('#include <cstdint>')
out.append('')
out.append('namespace graphics::compiled_shaders {')
out.append('')
for source, length, profile, data in shaders:
    out.append(f'inline constexpr uint8_t k{source:08X}_{profile}[{len(data)}] = {{')
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    out.append('};')
    out.append('')
out.append('struct Entry {')
out.append('  uint32_t source;  // the HLSL\'s address in the image')
out.append('  uint32_t length;  // its length, as the callers pass it')
out.append('  const char* profile;')
out.append('  const uint8_t* data;  // null: the end marker')
out.append('  uint32_t size;')
out.append('};')
out.append('')
out.append('inline constexpr Entry kShaders[] = {')
for source, length, profile, data in shaders:
    out.append(f'    {{0x{source:08X}, {length}, "{profile}", k{source:08X}_{profile}, {len(data)}}},')
out.append('    {0, 0, "", nullptr, 0},')
out.append('};')
out.append('')
out.append('}  // namespace graphics::compiled_shaders')
out.append('')

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'graphics',
                    'compiled_shaders.h')
with open(path, 'w', newline='\r\n') as f:
    f.write('\n'.join(out))
print(f'{len(shaders)} shaders written to {os.path.normpath(path)}')
