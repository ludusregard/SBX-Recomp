// A file's table entry: [file + 8 x ([file + count_at] + index + bias)].
uint32_t TableEntry(uint8_t* base, uint32_t file, uint32_t count_at, uint32_t index,
                    uint32_t bias) {
  return LoadU32(base, file + ((LoadU32(base, file + count_at) + index + bias) << 3));
}

// The 8-byte magic at `at`: four characters, a 0, then the version's
// three and a 0.
bool Magic(uint8_t* base, uint32_t at, const char (&magic)[8]) {
  for (uint32_t i = 0; i < 8; i++) {
    if (LoadU8(base, at + i) != uint8_t(magic[i])) {
      return false;
    }
  }
  return true;
}

// A node's entry in the movie's map (+65536 - 25652: sub_8211B4E0 with
// the key in the original's 96-byte frame at +80); 0 when there's none.
uint32_t NodeEntry(PPCContext& ctx, uint8_t* base, uint32_t movie, uint32_t key) {
  guest::StackFrame frame(ctx, 96);
  const uint32_t local = frame.Local(80);
  guest::StoreU32(base, local, key);
  ctx.r3.u64 = movie + 65536 - 25652;
  ctx.r4.u64 = local;
  sub_8211B4E0(ctx, base);
  return LoadU32(base, ctx.r3.u32);
}

